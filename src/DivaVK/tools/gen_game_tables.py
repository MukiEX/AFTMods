#!/usr/bin/env python3
"""Generates plugin/game_gl_tables.inc from DivaGL's wrap.cpp: the addresses of the game's
GL function-pointer slots (opengl32 import table and extension table) and of GLUT's
opengl32 imports, with the GL function each slot holds. The bridge writes DivaVK's
implementations into these slots directly, so it doesn't depend on how the game loaded them."""
import re, sys, pathlib

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '.')
wrap = (root / 'DivaGL' / 'wrap.cpp').read_text(errors='ignore')
game = re.findall(r'\)(0x00000001[0-9A-Fa-f]{8}); // ((?:gl|wgl)[A-Za-z0-9]+)', wrap)
glut = re.findall(r'divagl_((?:gl|wgl)[A-Za-z0-9]+)GLUT = \([A-Z0-9_]+\*\)\(glut_handle \+ (0x[0-9A-Fa-f]+)\)', wrap)
out = pathlib.Path(__file__).resolve().parent.parent / 'plugin' / 'game_gl_tables.inc'
lines = ['// Generated by tools/gen_game_tables.py from DivaGL/wrap.cpp - do not edit',
         '#ifdef DIVAVK_GAME_SLOT']
lines += [f'DIVAVK_GAME_SLOT({addr}, "{name}")' for addr, name in game]
lines += ['#endif', '#ifdef DIVAVK_GLUT_SLOT']
lines += [f'DIVAVK_GLUT_SLOT({off}, "{name}")' for name, off in glut]
lines += ['#endif', '']
out.write_text('\n'.join(lines))
print(f'{len(game)} game slots, {len(glut)} glut slots -> {out}')
