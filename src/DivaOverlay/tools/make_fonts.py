#!/usr/bin/env python3
"""Subsets LauncherFS's M PLUS Rounded 1c fonts to what DivaOverlay draws (Latin, Latin-1,
punctuation, arrows and a few shapes) and writes them as C arrays (res/ov_fonts.cpp), so
DivaLinux.dva and the preview tool carry them without a resource file.

    python3 tools/make_fonts.py        (needs fontTools: pip install fonttools)
"""
import os, sys
from fontTools import subset

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'LauncherFS', 'res')
OUT = os.path.join(HERE, '..', 'res', 'ov_fonts.cpp')
TEXT = ''.join(chr(c) for c in range(0x20, 0x7F)) + ''.join(chr(c) for c in range(0xA0, 0x180)) + \
    '–—‘’“”•…‹›←↑→↓□△○●✓✕×'

def sub(name):
    opts = subset.Options()
    opts.layout_features = ['kern', 'liga']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    opts.hinting = False
    font = subset.load_font(os.path.join(SRC, name), opts)
    s = subset.Subsetter(opts)
    s.populate(text=TEXT)
    s.subset(font)
    import io
    b = io.BytesIO()
    subset.save_font(font, b, opts)
    return b.getvalue()

def arr(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join(str(x) for x in data[i:i + 24]) + ',')
    return 'extern const unsigned char %s[] = {\n%s\n};\nextern const unsigned int %s_size = %d;\n' % (name, '\n'.join(lines), name, len(data))

bold = sub('MPLUSRounded1c-ExtraBold.ttf')
reg = sub('MPLUSRounded1c-Medium.ttf')
with open(OUT, 'w') as f:
    f.write('// Generated by tools/make_fonts.py from LauncherFS/res (M PLUS Rounded 1c, SIL Open Font\n'
            '// License 1.1: LauncherFS/res/OFL.txt), subset to Latin. Do not edit.\n\n')
    f.write(arr('dov_font_bold', bold) + '\n' + arr('dov_font_regular', reg))
print('bold %d bytes, regular %d bytes -> %s' % (len(bold), len(reg), OUT), file=sys.stderr)
