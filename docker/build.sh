#!/usr/bin/env bash
# Runs inside the container with the AFTMods checkout mounted at /src.
# Usage: build-aftmods [Release|Debug]   -> DVAs land in /src/out/
set -euo pipefail
CONFIG=${1:-Release}
SDK_TAG=vulkan-sdk-1.4.363.0
# FFmpeg headers for DivaLinux's movie player. They must come from the same FFmpeg as the DLLs
# it loads (avutil-61, swresample-7, swscale-10, avcodec-63, avformat-63): this is master
# from 2026-10-10, the build DivaMovie's FFmpeg player was tested with.
FFMPEG_COMMIT=ba987fe24d6713c4d4b3a15cebaeca18c41fbd31
DEPS=/src/.deps
cd /src

# The container runs as root (Wine's prefix lives in /root), so hand everything the build
# creates back to whoever owns the source folder when we exit, success or failure.
OWNER=$(stat -c %u:%g /src)
give_back() {
    chown -R "$OWNER" .deps bin out obj lib src/DivaVK/external/Vulkan-Headers src/DivaVK/lib src/LauncherFS/build 2>/dev/null || true
}
trap give_back EXIT

# Every cl.exe shares one wineserver, which holds all of their open files. Newer Docker
# (containerd 2.x) starts containers with a 1024 open-file soft limit, and a parallel build
# exhausts it: compiles then fail with "Cannot open include file" for headers that exist,
# or C1001 in p0io.cpp. Raise the limit before wineserver starts so it inherits it.
ulimit -n "$(ulimit -Hn)" 2>/dev/null || ulimit -n 65536 2>/dev/null || true
echo "== Open file limit: $(ulimit -n)"
if [ "$(ulimit -n)" -lt 8192 ]; then
    echo "   That's low for a parallel build; run with: docker run --ulimit nofile=65536:65536 ..." >&2
fi

# A persistent wineserver makes the many cl.exe/link.exe invocations much faster.
wineserver -p 2>/dev/null || true
$(command -v wine64 || command -v wine) wineboot >/dev/null 2>&1 || true

echo "== Fetching DivaVK dependencies ($SDK_TAG)"
mkdir -p "$DEPS"
[ -d "$DEPS/glslang" ] || git clone -q --depth 1 -b $SDK_TAG https://github.com/KhronosGroup/glslang.git "$DEPS/glslang"
[ -d src/DivaVK/external/Vulkan-Headers ] || \
    git clone -q --depth 1 -b $SDK_TAG https://github.com/KhronosGroup/Vulkan-Headers.git src/DivaVK/external/Vulkan-Headers

FFINC="$DEPS/ffmpeg-$FFMPEG_COMMIT/include"
if [ ! -f "$FFINC/libavcodec/avcodec.h" ]; then
    echo "== Fetching FFmpeg headers (${FFMPEG_COMMIT:0:7})"
    FFSRC="$DEPS/ffmpeg-src"
    rm -rf "$FFSRC" && mkdir -p "$FFSRC"
    git -C "$FFSRC" init -q
    git -C "$FFSRC" remote add origin https://github.com/FFmpeg/FFmpeg.git
    git -C "$FFSRC" fetch -q --depth 1 --filter=blob:none origin "$FFMPEG_COMMIT"
    git -C "$FFSRC" sparse-checkout set --no-cone '/libavutil/*.h' '/libavcodec/*.h' '/libavformat/*.h' \
        '/libswscale/*.h' '/libswresample/*.h'
    git -C "$FFSRC" checkout -q FETCH_HEAD
    mkdir -p "$FFINC"
    for lib in libavutil libavcodec libavformat libswscale libswresample; do
        mkdir -p "$FFINC/$lib" && cp "$FFSRC/$lib"/*.h "$FFINC/$lib/"
    done
    # Generated by FFmpeg's configure; x86-64 values.
    printf '#ifndef AVUTIL_AVCONFIG_H\n#define AVUTIL_AVCONFIG_H\n#define AV_HAVE_BIGENDIAN 0\n#define AV_HAVE_FAST_UNALIGNED 1\n#endif\n' \
        > "$FFINC/libavutil/avconfig.h"
    rm -rf "$FFSRC"
fi

# DivaLinux.dva is the plugin for Windows and Wine alike now. The plain-GL DivaGL.dva is
# retired from the default build; BUILD_DIVAGL=1 still builds it (its sources are DivaLinux's).
TARGETS=DivaLinux
[ "${BUILD_DIVAGL:-0}" = 1 ] && TARGETS="DivaGL DivaLinux"
echo "== Building KKdLib, AFTModsShared and $TARGETS (cl.exe via CMake/Ninja, no MSBuild)"
# MSBuild 18 can't run under Wine Mono (it loads Visual Studio telemetry assemblies that
# Build Tools doesn't ship), so CMakeLists.txt mirrors the solution's Release|x64 settings.
CC=cl CXX=cl cmake -S . -B "$DEPS/build-$CONFIG" -G Ninja \
    -DCMAKE_SYSTEM_NAME=Windows -DCMAKE_BUILD_TYPE=$CONFIG \
    -DDIVAVK_VULKAN_HEADERS_DIR=/src/src/DivaVK/external/Vulkan-Headers \
    -DDIVAVK_GLSLANG_DIR="$DEPS/glslang" \
    -DDIVALINUX_FFMPEG_INCLUDE_DIR="$FFINC"
# If a compile still fails to read a header under Wine, it's transient and Ninja resumes
# where it stopped, so retry a few times with fewer parallel compiles. JOBS overrides the
# starting parallelism (default: up to 8).
JOBS=${JOBS:-$(( $(nproc) < 8 ? $(nproc) : 8 ))}
for attempt in 1 2 3 4; do
    if cmake --build "$DEPS/build-$CONFIG" --target $TARGETS -- -j "$JOBS"; then
        break
    fi
    if [ "$attempt" = 4 ]; then
        echo "== Build failed 4 times. If it's the same file and error each time, it's a real error; otherwise try JOBS=4." >&2
        exit 1
    fi
    echo "== Build stopped (attempt $attempt); retrying from where it left off"
    JOBS=$(( JOBS > 2 ? JOBS / 2 : 1 ))
done

mkdir -p out
rm -f out/DivaGL.dva   # an old one would look current
for t in $TARGETS; do cp -v "bin/$t.dva" out/; done

# Launcher.dva (src/LauncherFS) is built with llvm-mingw, not cl.exe: it shares nothing with
# the game's STL, and MinGW's headers cover what it uses. llvm-mingw is fetched into .deps
# on first use (with Python: the image has no curl/xz). BUILD_LAUNCHER=0 skips it.
LLVM_MINGW_TAG=20251104
LLVM_MINGW="$DEPS/llvm-mingw-$LLVM_MINGW_TAG-ucrt-ubuntu-22.04-x86_64"
if [ "${BUILD_LAUNCHER:-1}" = 1 ]; then
    if [ ! -x "$LLVM_MINGW/bin/x86_64-w64-mingw32-clang++" ]; then
        echo "== Fetching llvm-mingw $LLVM_MINGW_TAG (for Launcher.dva)"
        python3 - "$LLVM_MINGW_TAG" "$DEPS" <<'PY'
import os, sys, tarfile, urllib.request
tag, deps = sys.argv[1], sys.argv[2]
name = f"llvm-mingw-{tag}-ucrt-ubuntu-22.04-x86_64.tar.xz"
url = f"https://github.com/mstorsjo/llvm-mingw/releases/download/{tag}/{name}"
path = os.path.join(deps, name)
urllib.request.urlretrieve(url, path)
with tarfile.open(path, "r:xz") as t:
    t.extractall(deps)
os.remove(path)
PY
    fi
    echo "== Building Launcher.dva (llvm-mingw)"
    (cd src/LauncherFS && LLVM_MINGW="$LLVM_MINGW" sh ./build-mingw.sh)
    cp -v src/LauncherFS/build/win/Launcher.dva out/
fi
echo "== Done: out/DivaLinux.dva (Windows and Wine/Proton: DivaGL on Vulkan + FFmpeg movies; replaces DivaGL.dva, DivaVK.dva and DivaMovie.dva)"
[ -f out/DivaGL.dva ] && echo "         out/DivaGL.dva (retired plain-OpenGL build, BUILD_DIVAGL=1)" || true
[ -f out/Launcher.dva ] && echo "         out/Launcher.dva (the fullscreen launcher)" || true
